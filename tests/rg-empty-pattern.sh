#!/usr/bin/env bash
# bin/rg: отказ на пустой шаблон называет инструмент для того, что агент собирался сделать (#89 п.1).
#
# Повод: три отказа за одну сессию `01a21957` («пустой шаблон совпадает с любой строкой — задайте,
# что искать»), и каждый раз целью было посчитать строки в файле. Правило «для числа строк — `wc -l`,
# а не `rg -c ''`» уже стояло в `docs/session-logs.md`, но на файлах репозитория не всплывало: агент
# встречал отказ, который говорил, чего нельзя, и молчал о том, что нужно.
#
# Проверяется: (1) отказ на пустой шаблон в аргументах; (2) отказ на `-e ''`; (3) оба называют
# `wc -l`; (4) непустой шаблон по-прежнему ищет.
# Exit 0 — всё сошлось; 1 — проверка упала.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
RG="$ROOT/bin/rg"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

fail() { echo "FAIL: $*" >&2; exit 1; }

printf 'one\ntwo\n' > "$WORK/file.txt"

refusal() {
	local out
	if out=$(cd "$WORK" && bash "$RG" "$@" 2>&1); then
		fail "вызов прошёл, а должен был отказать: rg $*"
	fi
	printf '%s\n' "$out"
}

out="$(refusal '' file.txt)"
[[ "$out" == *"пустой шаблон"* ]] || fail "отказ не назвал причину: $out"
[[ "$out" == *"wc -l"* ]] || fail "отказ не назвал wc -l: $out"

out="$(refusal -e '' file.txt)"
[[ "$out" == *"wc -l"* ]] || fail "отказ на -e '' не назвал wc -l: $out"

# Отказ считает сам сторож, а поиск — настоящий rg: на раннере без ripgrep вторая половина
# проверки невозможна (отказ на пустой шаблон приходит раньше поиска бинарника).
if ! hits=$(cd "$WORK" && bash "$RG" -c 'two' file.txt 2>&1); then
	case "$hits" in
		*"настоящий rg не найден"*) echo "SKIP: нет настоящего rg — проверена только сторона отказа"; exit 0 ;;
	esac
	fail "непустой шаблон должен искать: $hits"
fi
[[ "$hits" == "1" ]] || fail "rg -c по непустому шаблону вернул $hits вместо 1"

echo "OK: пустой шаблон отказан с подсказкой wc -l, непустой ищет"
